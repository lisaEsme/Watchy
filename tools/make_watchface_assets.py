#!/usr/bin/env python3
"""Turn our watch face design into data the watch can draw.

Reads (from watchface/design/):
  face.png                 200x200 black-and-white design
  PocketPixel-Regular.ttf  Pocket Pixel font (CC BY-SA 3.0, stuck-in-suburbia)

Writes (to watchface/):
  face_background.h  the design with the live areas (time, date, steps) blanked
  PocketPixel.h      the font in Adafruit GFX format, 1 screen pixel per font pixel
  face_layout.h      positions of the live areas, measured from the design

Run from the repository root:  python3 tools/make_watchface_assets.py
Needs: pip install pillow fonttools
"""
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "watchface" / "design"
OUT = ROOT / "watchface"

# Live areas in face.png, as (x0, y0, x1, y1) inclusive. These are erased from the
# background and redrawn by the watch with the real values.
LIVE_AREAS = {
    "TIME": (44, 38, 167, 81),    # "12:00"
    "DATE": (71, 87, 136, 98),    # "11 Nov 26"
    "STEPS": (154, 109, 198, 120),  # "10000" after the "Steps" label
    "SUNRISE": (158, 129, 198, 140),  # "00:00" after the "Sunrise" label (digits 1px closer)
}

FONT_GRID = 128  # Pocket Pixel is drawn on a 128-unit grid: one grid square = one pixel


def write_background():
    img = Image.open(DESIGN / "face.png").convert("L")
    assert img.size == (200, 200), "face.png must be 200x200"
    draw = ImageDraw.Draw(img)
    for x0, y0, x1, y1 in LIVE_AREAS.values():
        draw.rectangle((x0, y0, x1, y1), fill=255)
    px = img.load()
    data = []
    for y in range(200):
        for xb in range(0, 200, 8):
            byte = 0
            for bit in range(8):
                if px[xb + bit, y] < 128:  # black pixel
                    byte |= 0x80 >> bit
            data.append(byte)
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 25]) for i in range(0, len(data), 25)]
    (OUT / "face_background.h").write_text(
        "// Generated by tools/make_watchface_assets.py from watchface/design/face.png.\n"
        "// Do not edit by hand: change face.png and run the script again.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        "// 200x200, 1 bit per pixel, black = 1. Draw with display.drawBitmap(0, 0, ...).\n"
        "const unsigned char face_background[] PROGMEM = {\n  " + ",\n  ".join(lines) + "\n};\n"
    )


def glyph_pixels(font, cmap, pil_font, ch):
    """Return (width, height, xOffset, yOffset, xAdvance, rows) for one character."""
    name = cmap[ord(ch)]
    advance = round(font["hmtx"][name][0] / FONT_GRID)
    pen = BoundsPen(font.getGlyphSet())
    font.getGlyphSet()[name].draw(pen)
    if pen.bounds is None:  # e.g. space
        return 0, 0, 0, 0, advance, []
    xmin, ymin, xmax, ymax = (round(v / FONT_GRID) for v in pen.bounds)
    w, h = xmax - xmin, ymax - ymin
    # Render large (16 screen px per font pixel) and sample the centre of each square
    scale = 16
    pad = 4 * scale
    canvas = Image.new("L", ((w + 8) * scale + pad, (ymax + 8) * scale + 2 * pad), 0)
    baseline = pad + (ymax + 2) * scale
    ImageDraw.Draw(canvas).text((pad, baseline), ch, font=pil_font, fill=255, anchor="ls")
    cpx = canvas.load()
    rows = []
    for row in range(h):  # top to bottom
        y_units = ymax - row - 0.5
        cy = int(baseline - y_units * scale)
        rows.append([cpx[int(pad + (xmin + col + 0.5) * scale), cy] > 127 for col in range(w)])
    return w, h, xmin, -ymax, advance, rows


def write_font():
    path = DESIGN / "PocketPixel-Regular.ttf"
    font = TTFont(path)
    cmap = font.getBestCmap()
    pil_font = ImageFont.truetype(str(path), size=1024 // FONT_GRID * 16)  # 16 px per grid square
    bitmap, glyphs = [], []
    for code in range(0x20, 0x7F):
        w, h, xo, yo, adv, rows = glyph_pixels(font, cmap, pil_font, chr(code))
        bits = [b for r in rows for b in r]
        glyphs.append((len(bitmap), w, h, adv, xo, yo, chr(code)))
        for i in range(0, len(bits), 8):  # GFX glyph bitmaps are packed continuously
            chunk = bits[i:i + 8]
            bitmap.append(sum(0x80 >> j for j, b in enumerate(chunk) if b))
    y_advance = round((font["hhea"].ascent - font["hhea"].descent) / FONT_GRID) + 1
    bm = ", ".join(f"0x{b:02x}" for b in bitmap)
    gl = ",\n  ".join(
        f"{{ {o:4}, {w}, {h}, {a}, {xo}, {yo} }}  /* 0x{ord(c):02X} {c!r} */"
        for o, w, h, a, xo, yo, c in glyphs
    )
    (OUT / "PocketPixel.h").write_text(
        "// \"Pocket Pixel\" by stuck-in-suburbia (2011), built with FontStruct:\n"
        "//   http://fontstruct.com/fontstructions/show/460205\n"
        "// Licensed under Creative Commons Attribution-ShareAlike 3.0:\n"
        "//   http://creativecommons.org/licenses/by-sa/3.0/\n"
        "// Converted to Adafruit GFX format (1 screen pixel per font pixel) by\n"
        "// tools/make_watchface_assets.py; this converted font is shared under the same licence.\n"
        "// Scale it up with display.setTextSize(x, y) for crisp, blocky larger text.\n"
        "#pragma once\n#include <Adafruit_GFX.h>\n\n"
        f"const uint8_t PocketPixelBitmaps[] PROGMEM = {{\n  {bm}\n}};\n\n"
        "// bitmapOffset, width, height, xAdvance, xOffset, yOffset\n"
        f"const GFXglyph PocketPixelGlyphs[] PROGMEM = {{\n  {gl}\n}};\n\n"
        "const GFXfont PocketPixel PROGMEM = {\n"
        f"  (uint8_t *)PocketPixelBitmaps, (GFXglyph *)PocketPixelGlyphs, 0x20, 0x7E, {y_advance}\n}};\n"
    )


def write_layout():
    lines = [
        "// Generated by tools/make_watchface_assets.py: live areas measured in face.png.",
        "#pragma once",
        "",
    ]
    for name, (x0, y0, x1, y1) in LIVE_AREAS.items():
        lines += [
            f"#define {name}_LEFT    {x0}",
            f"#define {name}_TOP     {y0}",
            f"#define {name}_RIGHT   {x1}",
            f"#define {name}_BOTTOM  {y1}",
            "",
        ]
    (OUT / "face_layout.h").write_text("\n".join(lines))


if __name__ == "__main__":
    write_background()
    write_font()
    write_layout()
    print("Wrote watchface/face_background.h, watchface/PocketPixel.h and watchface/face_layout.h")
